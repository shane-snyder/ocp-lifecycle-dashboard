"""Regenerates every derived file in the repo.

    python3 hack/generate.py                     # write them
    python3 hack/generate.py --check             # CI: fail if any is stale
    python3 hack/generate.py --image quay.io/me/ocp-lifecycle-exporter:v1
                                                 # bake another image into the ACM policies

Needs kustomize, kubectl or oc on PATH for the ACM policies.

Outputs:
    dashboards/ocp-lifecycle.json                          import into any Grafana
    dashboards/ocp-lifecycle-otel.json                     the same, keyed on k8s_cluster_name (option 2)
    deploy/option-2-opentelemetry/grafana-operator/grafana-dashboard.yaml   its GrafanaDashboard
    deploy/grafana-dashboard/grafana-dashboard.yaml        Grafana Operator GrafanaDashboard
    deploy/option-3-acm/observability/grafana-dashboard.yaml   ACM Grafana ConfigMap
    deploy/option-3-acm/observability/metrics-allowlist.yaml   ACM metrics allowlist
    deploy/option-3-acm/policy-*.yaml                      ACM policies, from deploy/base + a component
"""
import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "hack"))
from gen_dashboard import dashboard  # noqa: E402

DEFAULT_IMAGE = "quay.io/rh_ee_ssnyder/ocp-lifecycle-dashboard"
GENERATED = "# Generated by hack/generate.py - edit the source and regenerate.\n"

# Both the Grafana Operator data sources in this repo use this uid.
DATASOURCE_UID = "ocp-lifecycle"
# k8s.cluster.name from the collector's resource detection, as Prometheus-style
# backends name it.
OTEL_CLUSTER_LABEL = "k8s_cluster_name"
# ACM observability's built-in Grafana data source.
ACM_DATASOURCE = ("000000001", "Observatorium")


def indent(text, n):
    pad = " " * n
    return "".join(pad + line + "\n" if line else "\n" for line in text.splitlines())


def dashboard_json(*args):
    return json.dumps(dashboard(*args), indent=2, ensure_ascii=False) + "\n"


def grafana_operator_dashboard(cluster_label="cluster"):
    otel = cluster_label != "cluster"
    return GENERATED + f"""\
# Red Hat lifecycle of each cluster's OpenShift version and installed
# operators{", told apart by OpenTelemetry's k8s_cluster_name" if otel else ""}.
# Selects the data source with uid ocp-lifecycle by default.
apiVersion: grafana.integreatly.org/v1beta1
kind: GrafanaDashboard
metadata:
  name: ocp-lifecycle{"-otel" if otel else ""}
spec:
  instanceSelector:
    matchLabels:
      dashboards: grafana
  resyncPeriod: 10m
  json: |
""" + indent(dashboard_json(DATASOURCE_UID, "OpenShift lifecycle", cluster_label), 4)


def acm_dashboard():
    return GENERATED + """\
# Adds the dashboard to ACM observability's Grafana, in the "Custom" folder,
# reading the fleet through its Observatorium data source.
apiVersion: v1
kind: ConfigMap
metadata:
  name: ocp-lifecycle
  namespace: open-cluster-management-observability
  labels:
    grafana-custom-dashboard: "true"
  annotations:
    observability.open-cluster-management.io/dashboard-folder: Custom
data:
  ocp-lifecycle.json: |
""" + indent(dashboard_json(*ACM_DATASOURCE), 4)


def metric_names():
    src = (ROOT / "ocp_lifecycle_exporter" / "metrics.py").read_text()
    prefix = re.search(r'PREFIX = "(\w+)"', src).group(1)
    return [prefix + n for n in re.findall(r'\.family\(\s*"(\w+)"', src)]


def acm_allowlist():
    names = indent("names:\n" + "".join(f"  - {n}\n" for n in metric_names()), 6)
    return GENERATED + """\
# Tells ACM observability to collect the exporter's series from every managed
# cluster, from the platform Prometheus (metrics_list.yaml) or user workload
# monitoring (uwl_metrics_list.yaml).
#
# The hub has exactly one ConfigMap with this name. If you already have one,
# merge these names into it instead of applying this file.
apiVersion: v1
kind: ConfigMap
metadata:
  name: observability-metrics-custom-allowlist
  namespace: open-cluster-management-observability
data:
  metrics_list.yaml: |
""" + names + "  uwl_metrics_list.yaml: |\n" + names


def kustomize_build(path):
    for cmd in (["kustomize", "build"], ["kubectl", "kustomize"], ["oc", "kustomize"]):
        if shutil.which(cmd[0]):
            return subprocess.run(cmd + [str(path)], check=True, capture_output=True, text=True).stdout
    sys.exit("generate.py: need kustomize, kubectl or oc on PATH")


def acm_policy(component, image):
    # kustomize only accepts relative paths, so the overlay lives in the repo.
    with tempfile.TemporaryDirectory(dir=ROOT / "deploy", prefix=".generate-") as tmp:
        repo, _, tag = image.rpartition(":") if ":" in image.split("/")[-1] else (image, "", "latest")
        (Path(tmp) / "kustomization.yaml").write_text(f"""\
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources: [../base]
components: [../components/{component}]
images:
  - name: {DEFAULT_IMAGE}
    newName: {repo}
    newTag: "{tag}"
""")
        docs = [d.strip("\n") for d in kustomize_build(tmp).split("\n---\n") if d.strip()]
    templates = "".join(
        "            - complianceType: musthave\n"
        "              objectDefinition:\n" + indent(doc, 16) for doc in docs)
    return GENERATED + f"""\
# Installs ocp-lifecycle-exporter (deploy/base + deploy/components/{component})
# on every cluster the ocp-lifecycle-exporter Placement selects, and removes
# it again if the policy is deleted.
apiVersion: policy.open-cluster-management.io/v1
kind: Policy
metadata:
  name: ocp-lifecycle-exporter
  namespace: ocp-lifecycle-policies
  annotations:
    policy.open-cluster-management.io/standards: NIST SP 800-53
    policy.open-cluster-management.io/categories: CM Configuration Management
    policy.open-cluster-management.io/controls: CM-2 Baseline Configuration
spec:
  remediationAction: enforce
  disabled: false
  policy-templates:
    - objectDefinition:
        apiVersion: policy.open-cluster-management.io/v1
        kind: ConfigurationPolicy
        metadata:
          name: ocp-lifecycle-exporter
          annotations:
            # The alert annotations use Prometheus' {{{{ $labels }}}} syntax,
            # which ACM would otherwise try to resolve as its own templates.
            policy.open-cluster-management.io/disable-templates: "true"
        spec:
          severity: low
          pruneObjectBehavior: DeleteIfCreated
          object-templates:
""" + templates


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if any generated file is out of date")
    ap.add_argument("--image", default=DEFAULT_IMAGE + ":latest", help="exporter image for the ACM policies")
    args = ap.parse_args()

    outputs = {
        "dashboards/ocp-lifecycle.json": dashboard_json(),
        "dashboards/ocp-lifecycle-otel.json": dashboard_json(None, None, OTEL_CLUSTER_LABEL),
        "deploy/grafana-dashboard/grafana-dashboard.yaml": grafana_operator_dashboard(),
        "deploy/option-2-opentelemetry/grafana-operator/grafana-dashboard.yaml":
            grafana_operator_dashboard(OTEL_CLUSTER_LABEL),
        "deploy/option-3-acm/observability/grafana-dashboard.yaml": acm_dashboard(),
        "deploy/option-3-acm/observability/metrics-allowlist.yaml": acm_allowlist(),
        "deploy/option-3-acm/policy-platform-monitoring.yaml": acm_policy("platform-monitoring", args.image),
        "deploy/option-3-acm/policy-user-workload-monitoring.yaml": acm_policy("user-workload-monitoring", args.image),
    }
    stale = []
    for rel, text in outputs.items():
        path = ROOT / rel
        if path.exists() and path.read_text() == text:
            continue
        stale.append(rel)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    for rel in stale:
        print(("stale: " if args.check else "wrote: ") + rel)
    if args.check and stale:
        sys.exit("run python3 hack/generate.py and commit the result")


if __name__ == "__main__":
    main()
